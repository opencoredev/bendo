import type { Manifest } from "./manifest.ts";

/**
 * Prints a JSON value parsed from the manifest as a TypeScript literal.
 * `__proto__` becomes a computed key: in a plain object literal it would set
 * the prototype instead of creating the own property JSON.parse created.
 * JSON.parse turns overflowing numbers into Infinity, which JSON cannot print.
 */
function literal(value: unknown): string {
  if (value === null) return "null";
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
  switch (typeof value) {
    case "boolean":
    case "string":
      return JSON.stringify(value);
    case "number":
      return Number.isFinite(value) ? String(value) : value > 0 ? "Infinity" : "-Infinity";
    case "object":
      return `{ ${Object.entries(value)
        .map(
          ([key, item]) =>
            `${key === "__proto__" ? '["__proto__"]' : JSON.stringify(key)}: ${literal(item)}`,
        )
        .join(", ")} }`;
    default:
      throw new Error(`Invalid route manifest: ${typeof value} is not a JSON value`);
  }
}

/**
 * The runtime half of `bendo gen`: one row per manifest route, in registration
 * order, with the response schema when the route has one. The typed client
 * validates response bodies against it (docs/client.md). No imports, so the
 * file works without the bendo package on the import path.
 */
export function emitResponseSchemas(manifest: Manifest): string {
  const rows = manifest.routes.map((route) => {
    const response = route.schemas.response;
    const fields = [
      `method: ${JSON.stringify(route.method)}`,
      `path: ${JSON.stringify(route.path)}`,
      `all: ${route.all}`,
      ...(response === undefined ? [] : [`response: ${literal(response)}`]),
    ];
    return `  { ${fields.join(", ")} },`;
  });
  return `// Generated by bendo gen. Do not edit.
// Response schemas for the typed client: docs/client.md (Bendo toolkit).

export const schemas: ReadonlyArray<{
  readonly method: string;
  readonly path: string;
  readonly all: boolean;
  readonly response?: boolean | { readonly [keyword: string]: unknown };
}> = [${rows.length === 0 ? "" : `\n${rows.join("\n")}\n`}];
`;
}
