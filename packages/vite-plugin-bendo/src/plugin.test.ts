// BND-59: the plugin's hooks, run inside a real Vite server without a port,
// plus the compile queue, the cache and the diagnostic locator.
import { afterAll, beforeAll, expect, test } from "bun:test";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  createServer,
  type HmrContext,
  type ModuleNode,
  type Plugin,
  type ViteDevServer,
} from "vite";
import type { CompiledShared } from "bendo/shared";
import bendo, { Compiler, Gate, bendFile, declarationPath, locate, resolveBend } from "./index.ts";
import { findBendPath } from "./compiler.ts";
import { copyFixture } from "./fixture.ts";

const app = copyFixture("unit");
const plugin = bendo({ diskCache: false });
let server: ViteDevServer;

beforeAll(async () => {
  server = await createServer({
    root: app.root,
    configFile: false,
    logLevel: "silent",
    cacheDir: app.path(".vite"),
    server: { middlewareMode: true, ws: false, watch: null },
    plugins: [plugin],
  });
});
afterAll(async () => {
  await server.close();
  app[Symbol.dispose]();
});

function handler(hook: Plugin["handleHotUpdate"]): (context: HmrContext) => unknown {
  if (hook === undefined) throw new Error("no handleHotUpdate hook");
  const fn = typeof hook === "function" ? hook : hook.handler;
  return (context) => Reflect.apply(fn, undefined, [context]);
}

function hotContext(file: string, modules: ModuleNode[] = []): HmrContext {
  return {
    file,
    timestamp: Date.now(),
    modules,
    read: async () => "",
    server,
  };
}

test("bendFile accepts .bend ids and leaves asset queries to Vite", () => {
  expect(bendFile("/a/x.bend")).toBe("/a/x.bend");
  expect(bendFile("/a/x.bend?import&t=1")).toBe("/a/x.bend");
  expect(bendFile("/a/x.bend?raw")).toBeUndefined();
  expect(bendFile("/a/x.bend?url")).toBeUndefined();
  expect(bendFile("/a/x.ts")).toBeUndefined();
  expect(declarationPath("/a/x.bend")).toBe("/a/x.d.bend.ts");
});

test("resolveBend resolves relative, root-relative and absolute imports", () => {
  const handle = app.path("shared/handle.bend");
  const main = app.path("src/main.ts");
  expect(resolveBend("../shared/handle.bend", main, app.root)).toBe(handle);
  expect(resolveBend("../shared/handle.bend?import", `${main}?t=1`, app.root)).toBe(handle);
  expect(resolveBend("./rules.bend", handle, app.root)).toBe(app.path("shared/rules.bend"));
  expect(resolveBend("/shared/handle.bend", undefined, app.root)).toBe(handle);
  expect(resolveBend(handle, main, app.root)).toBe(handle);
  expect(resolveBend("../shared/missing.bend", main, app.root)).toBeUndefined();
  expect(resolveBend("some-package/x.bend", main, app.root)).toBeUndefined();
  expect(resolveBend("../shared/handle.bend?raw", main, app.root)).toBeUndefined();
});

test("resolveId runs through Vite's plugin container", async () => {
  const resolved = await server.pluginContainer.resolveId(
    "../shared/handle.bend",
    app.path("src/main.ts"),
  );
  expect(resolved?.id).toBe(app.path("shared/handle.bend"));
});

test("load compiles a .bend file to an ES module and writes its declarations", async () => {
  const loaded = await server.pluginContainer.load(app.path("shared/handle.bend"));
  const code = typeof loaded === "string" ? loaded : loaded?.code;
  expect(code).toContain("export default $0bendo;");
  expect(code).toMatch(/export \{ .*\$0n\d+ as check.* \};/);
  const types = app.read("shared/handle.d.bend.ts");
  expect(types).toContain("// Generated by vite-plugin-bendo from handle.bend.");
  expect(types).toContain("export declare function check(name: string): boolean;");
  expect(types).toContain("export declare function headline(): string;");
});

test("load leaves other files alone", async () => {
  expect(await server.pluginContainer.load(app.path("src/main.ts"))).toBeNull();
});

test("load reports a compile error with its file, line and column", async () => {
  const source = app.read("shared/rules.bend");
  app.edit("shared/rules.bend", '"Pick a handle"', "42");
  try {
    const failure: unknown = await server.pluginContainer.load(app.path("shared/handle.bend")).then(
      () => undefined,
      (error: unknown) => error,
    );
    expect(failure).toBeInstanceOf(Error);
    expect(failure).toMatchObject({
      plugin: "vite-plugin-bendo",
      loc: { file: app.path("shared/rules.bend"), line: 9, column: 3 },
    });
    expect(String(Reflect.get(Object(failure), "message"))).toContain("expected : String");
    expect(String(Reflect.get(Object(failure), "frame"))).toContain("9>|   42");
  } finally {
    app.write("shared/rules.bend", source);
  }
});

test("handleHotUpdate returns the importing module when a dependency changes", async () => {
  const hot = handler(plugin.handleHotUpdate);
  await server.transformRequest("/shared/handle.bend");
  const [module] = server.moduleGraph.getModulesByFile(app.path("shared/handle.bend")) ?? [];
  expect(module).toBeDefined();
  // A file outside every graph falls through to Vite.
  expect(await hot(hotContext(app.path("src/style.css")))).toBeUndefined();
  app.edit("shared/rules.bend", '"Pick a handle"', '"Choose a handle"');
  const modules: unknown = await hot(hotContext(app.path("shared/rules.bend")));
  expect(modules).toEqual([module]);
  expect(app.read("shared/handle.d.bend.ts")).toContain("headline");
});

test("handleHotUpdate sends a broken build to the overlay and updates nothing", async () => {
  const sent: unknown[] = [];
  const send = server.ws.send;
  server.ws.send = (...args: unknown[]) => {
    sent.push(args[0]);
  };
  try {
    app.edit(
      "shared/handle.bend",
      "def check(name: String) -> Bool:",
      "def check(name: String) -> Bool\n",
    );
    const modules: unknown = await handler(plugin.handleHotUpdate)(
      hotContext(app.path("shared/handle.bend")),
    );
    expect(modules).toEqual([]);
    expect(sent).toHaveLength(1);
    expect(sent[0]).toMatchObject({
      type: "error",
      err: { plugin: "vite-plugin-bendo", loc: { file: app.path("shared/handle.bend") } },
    });
  } finally {
    server.ws.send = send;
  }
});

function fake(entry: string): CompiledShared {
  return {
    source: entry,
    module: `export default ${JSON.stringify(entry)};`,
    declarations: "",
    named: [],
    warnings: [],
  };
}

function scratch(): {
  dir: string;
  file: (name: string, text: string) => string;
  [Symbol.dispose]: () => void;
} {
  const dir = mkdtempSync(join(tmpdir(), "bendo-vite-unit-"));
  return {
    dir,
    file(name, text) {
      const path = join(dir, name);
      writeFileSync(path, text);
      return path;
    },
    [Symbol.dispose]: () => rmSync(dir, { recursive: true, force: true }),
  };
}

test("the compiler runs one Bend process at a time and never repeats an unchanged graph", async () => {
  using dir = scratch();
  const files = ["a", "b", "c"].map((name) =>
    dir.file(`${name}.bend`, `def ${name}() -> Nat:\n  1n\n`),
  );
  const compiler = new Compiler({
    bend: "bend",
    cacheDir: undefined,
    concurrency: 1,
    compile: async (entry) => {
      await Bun.sleep(20);
      return fake(entry);
    },
  });
  const outcomes = await Promise.all([...files, ...files].map((file) => compiler.compile(file)));
  expect(outcomes.every((outcome) => outcome.kind === "compiled")).toBe(true);
  expect(compiler.compiles).toBe(3);
  expect(compiler.peakConcurrency).toBe(1);
  await compiler.compile(files[0] ?? "");
  expect(compiler.compiles).toBe(3);
  dir.file("a.bend", "def a() -> Nat:\n  2n\n");
  await compiler.compile(files[0] ?? "");
  expect(compiler.compiles).toBe(4);
});

test("an edited import invalidates its importer, and the disk cache survives a restart", async () => {
  using dir = scratch();
  const lib = dir.file("lib.bend", "def one() -> Nat:\n  1n\n");
  const main = dir.file(
    "main.bend",
    "import ./lib.bend as Lib\n\ndef two() -> Nat:\n  Lib.one()\n",
  );
  const cacheDir = join(dir.dir, "cache");
  let compiles = 0;
  const make = () =>
    new Compiler({
      bend: "bend",
      cacheDir,
      concurrency: 1,
      compile: async (entry) => {
        compiles++;
        return fake(entry);
      },
    });
  const first = make();
  await first.compile(main);
  expect(first.importersOf(lib)).toEqual([main]);
  expect(first.importersOf(main)).toEqual([main]);
  dir.file("lib.bend", "def one() -> Nat:\n  3n\n");
  await first.compile(main);
  expect(compiles).toBe(2);
  const restarted = make();
  const outcome = await restarted.compile(main);
  expect(outcome.kind).toBe("compiled");
  expect(compiles).toBe(2);
  expect(existsSync(cacheDir)).toBe(true);
});

