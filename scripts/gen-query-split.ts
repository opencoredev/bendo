// Generates proof/query-split.bend: Url.parse_pairs' "&" splitter and "="
// field splitter equal the independent pieces/name/value of
// proof/query-spec.bend for every octet list (BND-92).
//
// The literal 38 ("&") and 61 ("=") patterns compile to tries over the head
// octet's 32 bits, low bit first. Implementation and spec match the same
// literal, so the proof walks the same path, stops where no literal shares
// the prefix (both sides take their default row there) and finishes the
// literal's own branch at bit 32.
//
//   bun scripts/gen-query-split.ts > proof/query-split.bend

const lines: string[] = [];
const emit = (line: string): void => {
  lines.push(line);
};
const flag = (b: boolean): string => (b ? "True{}" : "False{}");
const L = "List<&2, U32>";
const LL = "List<&2, List<&2, U32>>";

function partial(prefix: boolean[], rest: string): string {
  return prefix.reduceRight((acc, b) => `WCon{${flag(b)}, ${acc}}`, rest);
}

// The head trie for `literal`, starting at word variable w0. `leaf(head)`
// closes a branch where the default row fires; `hit(indent)` emits the
// branch where the head is exactly the literal.
function headTrie(
  literal: number,
  indent: number,
  leaf: (head: string) => string,
  hit: (indent: number) => void,
): void {
  const want = [...Array(32).keys()].map((i) => ((literal >> i) & 1) === 1);
  const walk = (depth: number, prefix: boolean[], pad: number): void => {
    const sp = " ".repeat(pad);
    if (depth === 32) {
      emit(`${sp}match w32:`);
      emit(`${sp} case WNil{}:`);
      hit(pad + 2);
      return;
    }
    emit(`${sp}match w${depth}:`);
    for (const b of [true, false]) {
      emit(`${sp} case WCon{${flag(b)}, +w${depth + 1}}:`);
      if (b === want[depth]) walk(depth + 1, [...prefix, b], pad + 2);
      else emit(`${sp}  ${leaf(`U32{${partial([...prefix, b], `w${depth + 1}`)}}`)}`);
    }
  };
  walk(0, [], indent);
}

emit(`# BND-92: the raw query parser's "&" and "=" splitters equal the
# independent pieces, name and value of proof/query-spec.bend.
#
# GENERATED by scripts/gen-query-split.ts. Do not edit by hand.
import Base
import ../src/data/urlencoded.bend as Url
import ./query-spec.bend as QSpec

# The implementation's current piece, reversed, in front of the spec's
# first piece.
def join(cur: ${L}, ps: ${LL}) -> ${LL}:
  match ps:
    case Nil{}: [List.reverse(&2, U32, cur)]
    case p <> rest: List.reverse.go(&2, U32, cur, p) <> rest

def join_grow(+b: U32, +cur: ${L}, +ps: ${LL}) -> {join(b <> cur, ps) == join(cur, QSpec.grow(b, ps)) : ${LL}}:
  match ps:
    case Nil{}: {==}
    case p <> rest: {==}

def join_grow_nil(+b: U32, +ps: ${LL}) -> {join([], QSpec.grow(b, ps)) == QSpec.grow(b, ps) : ${LL}}:
  match ps:
    case Nil{}: {==}
    case p <> rest: {==}

# The spec never returns an empty list of pieces.
def join_pieces(+xs: ${L}) -> {join([], QSpec.pieces(xs)) == QSpec.pieces(xs) : ${LL}}:
  match xs:
    case Nil{}: {==}
    case U32{+w0} <> +t:`);
headTrie(
  38,
  6,
  (head) => `join_grow_nil(${head}, QSpec.pieces(t))`,
  (pad) => emit(`${" ".repeat(pad)}{==}`),
);
emit(``);

const splitGoal = (xs: string, cur: string, parts: string): string =>
  `{Url.split_go(${xs}, ${cur}, ${parts}) == List.reverse.go(&2, ${L}, ${parts}, join(${cur}, QSpec.pieces(${xs}))) : ${LL}}`;
emit(`# The splitter's loop is the spec with its finished pieces, reversed, in
# front and its current piece glued to the spec's first.
def split(+xs: ${L}, +cur: ${L}, +parts: ${LL}) -> ${splitGoal("xs", "cur", "parts")}:
  match xs:
    case Nil{}: {==}
    case U32{+w0} <> +t:`);
headTrie(
  38,
  6,
  (head) =>
    `Equal.trans(${LL}, Url.split_go(t, ${head} <> cur, parts), List.reverse.go(&2, ${L}, parts, join(${head} <> cur, QSpec.pieces(t))), List.reverse.go(&2, ${L}, parts, join(cur, QSpec.grow(${head}, QSpec.pieces(t)))), split(t, ${head} <> cur, parts), Equal.cong(${LL}, ${LL}, z => List.reverse.go(&2, ${L}, parts, z), join(${head} <> cur, QSpec.pieces(t)), join(cur, QSpec.grow(${head}, QSpec.pieces(t))), join_grow(${head}, cur, QSpec.pieces(t))))`,
  (pad) =>
    emit(
      `${" ".repeat(pad)}Equal.trans(${LL}, Url.split_go(t, [], List.reverse(&2, U32, cur) <> parts), List.reverse.go(&2, ${L}, List.reverse(&2, U32, cur) <> parts, join([], QSpec.pieces(t))), List.reverse.go(&2, ${L}, parts, List.reverse(&2, U32, cur) <> QSpec.pieces(t)), split(t, [], List.reverse(&2, U32, cur) <> parts), Equal.cong(${LL}, ${LL}, z => List.reverse.go(&2, ${L}, parts, List.reverse(&2, U32, cur) <> z), join([], QSpec.pieces(t)), QSpec.pieces(t), join_pieces(t)))`,
    ),
);
emit(``);
emit(`def split_equiv(+xs: ${L}) -> {Url.split(xs) == QSpec.pieces(xs) : ${LL}}:
  Equal.trans(${LL}, Url.split(xs), join([], QSpec.pieces(xs)), QSpec.pieces(xs), split(xs, [], []), join_pieces(xs))
`);

const P = `${L} & ${L}`;
emit(`# The field splitter's loop is the spec with the name read so far, reversed,
# in front.
def field(+xs: ${L}, +rev: ${L}) -> {Url.field_go(xs, rev) == (List.reverse.go(&2, U32, rev, QSpec.name(xs)), QSpec.value(xs)) : ${P}}:
  match xs:
    case Nil{}: {==}
    case U32{+w0} <> +t:`);
headTrie(
  61,
  6,
  (head) => `field(t, ${head} <> rev)`,
  (pad) => emit(`${" ".repeat(pad)}{==}`),
);
emit(``);
emit(`def field_equiv(+xs: ${L}) -> {Url.field(xs) == (QSpec.name(xs), QSpec.value(xs)) : ${P}}:
  field(xs, [])`);

process.stdout.write(lines.join("\n") + "\n");

export {};
