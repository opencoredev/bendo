import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { parseManifest } from "../packages/bendo/src/manifest.ts";
import { emitRouteTypes } from "../packages/bendo/src/route-types.ts";

// Run with: timeout 30s bun scripts/route-types-bench.ts
// Every leaf is accessed and called so tsc must instantiate the Eden sketch.
const directory = mkdtempSync(join(tmpdir(), "bendo-routes-bench-"));
try {
  const routes = Array.from({ length: 100 }, (_, index) => ({
    method: "POST",
    path: `/teams/:team/items/item${index}`,
    params: ["team"],
    schemas: {
      params: {
        type: "object",
        properties: { team: { type: "string" } },
        required: ["team"],
        additionalProperties: false,
      },
      body: {
        type: "object",
        properties: { title: { type: "string" }, done: { type: "boolean", default: false } },
        required: ["title"],
        additionalProperties: false,
      },
      response: {
        type: "object",
        properties: { id: { type: "integer" }, title: { type: "string" } },
        required: ["id", "title"],
        additionalProperties: false,
      },
    },
  }));
  writeFileSync(
    join(directory, "routes.ts"),
    emitRouteTypes(parseManifest(JSON.stringify({ bendo: 1, routes }))),
  );
  writeFileSync(
    join(directory, "consumer.ts"),
    `import type { Routes } from "./routes";
type Row = { method: string; path: string; input: unknown; output: { response: unknown } };
type Path<P extends string, Leaf> = P extends \`/\${infer Rest}\` ? Path<Rest, Leaf> : P extends \`\${infer Head}/\${infer Tail}\` ? { [K in Head]: Path<Tail, Leaf> } : { [K in P]: Leaf };
type Endpoint<R extends Row> = R extends Row ? Path<R["path"], { [M in Lowercase<R["method"]>]: (input: Omit<R["input"], "response">) => Promise<R["output"]["response"]> }> : never;
type Merge<U> = (U extends unknown ? (value: U) => void : never) extends (value: infer I) => void ? I : never;
type Eden = Merge<Endpoint<Routes>>;
declare const client: Eden;
${routes.map((_, index) => `const response${index}: Promise<{ id: number; title: string }> = client.teams[":team"].items.item${index}.post({ params: { team: "demo" }, query: undefined, headers: undefined, body: { title: "hello" } });`).join("\n")}
// @ts-expect-error unknown route
client.teams[":team"].items.missing.post({});
// @ts-expect-error wrong body field
client.teams[":team"].items.item0.post({ params: { team: "demo" }, query: undefined, headers: undefined, body: { title: 1 } });
`,
  );
  writeFileSync(
    join(directory, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        strict: true,
        noEmit: true,
        types: [],
        target: "ES2023",
        module: "Preserve",
        moduleResolution: "bundler",
      },
      files: ["consumer.ts"],
    }),
  );
  const result = Bun.spawnSync(
    [
      "/usr/bin/time",
      "-f",
      "wall_seconds=%e max_rss_kib=%M",
      process.execPath,
      resolve(import.meta.dir, "../node_modules/typescript/bin/tsc"),
      "-p",
      directory,
      "--extendedDiagnostics",
    ],
    { stdout: "pipe", stderr: "pipe", timeout: 20_000 },
  );
  console.log(
    `100 routes, ${readFileSync(join(directory, "routes.ts")).length} generated bytes, 100 Eden calls`,
  );
  console.log(result.stdout.toString());
  console.log(result.stderr.toString());
  if (result.exitCode !== 0) process.exitCode = result.exitCode ?? 1;
} finally {
  rmSync(directory, { recursive: true, force: true });
}
