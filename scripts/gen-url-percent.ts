// Generates proof/url-percent.bend: Url.percent_decode in query mode equals
// the independent Spec.unpercent for every octet list.
//
// Two kinds of case split appear. The literal 37 ('%') pattern compiles to
// a trie over the head's 32 bits, low bit first, so the proof walks the same
// path and stops where no literal shares the prefix. Hex digit tests are
// U32 comparisons, which Word.cmp decides from the top bit, so those proofs
// split the top 24 bits first and then all 8 low bits.
//
//   bun scripts/gen-url-percent.ts > proof/url-percent.bend

const lines: string[] = [];
const emit = (line: string): void => {
  lines.push(line);
};

const R = "Result<&2, &2, Url.Error, List<&2, U32>>";
const L = "List<&2, U32>";
const go = (xs: string, state: string): string => `Url.percent_decode_go(${xs}, False{}, ${state})`;
const percentBits = [...Array(32).keys()].map((i) => ((37 >> i) & 1) === 1);
const flag = (b: boolean): string => (b ? "True{}" : "False{}");

function isHex(code: number): boolean {
  return (code >= 48 && code <= 57) || (code >= 65 && code <= 70) || (code >= 97 && code <= 102);
}

function nibble(code: number): number {
  if (code <= 57) return code - 48;
  if (code <= 70) return code - 55;
  return code - 87;
}

// A word whose bits 0..k-1 are fixed by `prefix` and whose rest is `w`.
function partial(prefix: boolean[], rest: string): string {
  return prefix.reduceRight((acc, b) => `WCon{${flag(b)}, ${acc}}`, rest);
}

// The head trie for the literal 37. `leaf(head)` closes a branch where the
// default row fires for the given head term; `hit(indent)` emits the code
// for the branch where the head is exactly 37.
function headTrie(
  indent: number,
  leaf: (head: string) => string,
  hit: (indent: number) => void,
): void {
  const walk = (depth: number, prefix: boolean[], pad: number): void => {
    const sp = " ".repeat(pad);
    if (depth === 32) {
      emit(`${sp}match w32:`);
      emit(`${sp} case WNil{}:`);
      hit(pad + 2);
      return;
    }
    const want = percentBits[depth] ?? false;
    emit(`${sp}match w${depth}:`);
    for (const b of [true, false]) {
      if (b === want) {
        emit(`${sp} case WCon{${flag(b)}, +w${depth + 1}}:`);
        walk(depth + 1, [...prefix, b], pad + 2);
      } else {
        emit(`${sp} case WCon{${flag(b)}, +w${depth + 1}}:`);
        emit(`${sp}  ${leaf(`U32{${partial([...prefix, b], `w${depth + 1}`)}}`)}`);
      }
    }
  };
  walk(0, [], indent);
}

// MSB-first split over a byte's bits b31..b0; `low(code)` closes a fully
// known low byte, `high()` closes a branch with a set bit above bit 7.
function msbSplit(indent: number, high: () => string, low: (code: number) => string): void {
  const walk = (bit: number, code: number, pad: number): void => {
    const sp = " ".repeat(pad);
    emit(`${sp}match b${bit}:`);
    if (bit >= 8) {
      emit(`${sp} case True{}: ${high()}`);
      emit(`${sp} case False{}:`);
      walk(bit - 1, code, pad + 2);
      return;
    }
    for (const b of [true, false]) {
      const next = code + (b ? 1 << bit : 0);
      if (bit === 0) {
        emit(`${sp} case ${flag(b)}: ${low(next)}`);
      } else {
        emit(`${sp} case ${flag(b)}:`);
        walk(bit - 1, next, pad + 2);
      }
    }
  };
  walk(31, 0, indent);
}

const bitParams = [...Array(32).keys()]
  .reverse()
  .map((i) => `+b${i}: Bool`)
  .join(", ");
const bitArgs = [...Array(32).keys()]
  .reverse()
  .map((i) => `b${i}`)
  .join(", ");
const bitWord = [...Array(32).keys()].reduceRight((acc, i) => `WCon{b${i}, ${acc}}`, "WNil{}");
const bitPattern = [...Array(32).keys()].reduceRight((acc, i) => `WCon{+b${i}, ${acc}}`, "WNil{}");
const byteA = `U32{${bitWord}}`;

emit(`# BND-87: Url.percent_decode in query mode equals the independent
# Spec.unpercent for every octet list, so Url.decode's first stage is
# specified without the library decoder.
#
# GENERATED by scripts/gen-url-percent.ts. Do not edit by hand.
import Base
import ../src/data/urlencoded.bend as Url
import ../src/http/bytes.bend as Bytes
import ./url-decode-spec.bend as Spec

# The implementation's prefix of reversed octets, in front of the spec.
def prepend(rev: ${L}, r: ${R}) -> ${R}:
  match r:
    case Fail{e}: Fail{e}
    case Done{ys}: Done{List.reverse.go(&2, U32, rev, ys)}

def prepend_nil(+r: ${R}) -> {prepend([], r) == r : ${R}}:
  match r:
    case Fail{e}: {==}
    case Done{ys}: {==}

def shift(+b: U32, +rev: ${L}, +r: ${R}) -> {prepend(b <> rev, r) == prepend(rev, Spec.literal(b, r)) : ${R}}:
  match r:
    case Fail{e}: {==}
    case Done{ys}: {==}

def plus_off_go(+b: U32, x: Bool) -> {Url.plus_byte(b, x && False{}) == b : U32}:
  match x:
    case False{}: {==}
    case True{}: {==}

# In query mode "+" is an ordinary octet.
def plus_off(+b: U32) -> {Url.plus_byte(b, U32.is_eq(b, 43) && False{}) == b : U32}:
  plus_off_go(b, U32.is_eq(b, 43))

def lit_step(+b: U32, +t: ${L}, +rev: ${L}, ih: {${go("t", "Done{b <> rev}")} == prepend(b <> rev, Spec.unpercent(t)) : ${R}}) -> {${go("t", "Done{Url.plus_byte(b, U32.is_eq(b, 43) && False{}) <> rev}")} == prepend(rev, Spec.literal(b, Spec.unpercent(t))) : ${R}}:
  %Equal.sym(U32, Url.plus_byte(b, U32.is_eq(b, 43) && False{}), b, plus_off(b)) : {${go("t", "Done{_ <> rev}")} == prepend(rev, Spec.literal(b, Spec.unpercent(t))) : ${R}}
  Equal.trans(${R}, ${go("t", "Done{b <> rev}")}, prepend(b <> rev, Spec.unpercent(t)), prepend(rev, Spec.literal(b, Spec.unpercent(t))), ih, shift(b, rev, Spec.unpercent(t)))

def hpick(+c: U32, ok: Bool) -> Maybe<&2, U32>:
  match ok:
    case True{}: Some{Url.unhex(c)}
    case False{}: None{}
`);

// ---- hex digits ----
emit(`# The spec's hex digit value is the implementation's, for every U32.`);
emit(
  `def hex_bits(${bitParams}) -> {Spec.hexdig(${byteA}) == hpick(${byteA}, Bytes.hex(${byteA})) : Maybe<&2, U32>}:`,
);
msbSplit(
  2,
  () => "{==}",
  () => "{==}",
);
emit(``);
emit(`def hex(+c: U32) -> {Spec.hexdig(c) == hpick(c, Bytes.hex(c)) : Maybe<&2, U32>}:`);
emit(`  match c:`);
emit(`    case U32{${bitPattern}}:`);
emit(`      hex_bits(${bitArgs})`);
emit(``);

// ---- failure persists ----
emit(`# A failed state stays failed, whatever octets follow.`);
emit(`def fail_stays(+xs: ${L}, +e: Url.Error) -> {${go("xs", "Fail{e}")} == Fail{e} : ${R}}:`);
emit(`  match xs:`);
emit(`    case Nil{}: {==}`);
emit(`    case U32{+w0} <> +t:`);
headTrie(
  6,
  () => "{==}",
  (pad) => {
    const sp = " ".repeat(pad);
    emit(`${sp}match t:`);
    emit(`${sp} case Nil{}: {==}`);
    emit(`${sp} case +a <> Nil{}: {==}`);
    emit(`${sp} case +a <> +b <> +u: {==}`);
  },
);
emit(``);

// ---- escapes, with a known high digit ----
const IH = (t: string): string =>
  `@r:${L} -> {${go(t, "Done{r}")} == prepend(r, Spec.unpercent(${t})) : ${R}}`;
emit(`def esc_lo(+a: U32, +va: U32, +b: U32, +t: ${L}, +rev: ${L}, sh: {(Url.unhex(a) << 4n : U32) == (va * 16 : U32) : U32}, y: Bool, ey: {Bytes.hex(b) == y : Bool}, ih: ${IH("t")}) -> {${go("t", "Url.percent_step(a, b, rev, y)")} == prepend(rev, Spec.escaped(Some{va}, hpick(b, y), Spec.unpercent(t))) : ${R}}:
  match y:
    case False{}:
      fail_stays(t, Url.InvalidPercent{})
    case True{}:
      %Equal.sym(U32, (Url.unhex(a) << 4n : U32), (va * 16 : U32), sh) : {${go("t", "Done{(_ + Url.unhex(b) : U32) <> rev}")} == prepend(rev, Spec.literal((va * 16 + Url.unhex(b) : U32), Spec.unpercent(t))) : ${R}}
      Equal.trans(${R}, ${go("t", "Done{(va * 16 + Url.unhex(b) : U32) <> rev}")}, prepend((va * 16 + Url.unhex(b) : U32) <> rev, Spec.unpercent(t)), prepend(rev, Spec.literal((va * 16 + Url.unhex(b) : U32), Spec.unpercent(t))), ih((va * 16 + Url.unhex(b) : U32) <> rev), shift((va * 16 + Url.unhex(b) : U32), rev, Spec.unpercent(t)))

def esc_hi(+a: U32, +va: U32, +b: U32, +t: ${L}, +rev: ${L}, sh: {(Url.unhex(a) << 4n : U32) == (va * 16 : U32) : U32}, ih: ${IH("t")}) -> {${go("t", "Url.percent_step(a, b, rev, Bytes.hex(b))")} == prepend(rev, Spec.escaped(Some{va}, Spec.hexdig(b), Spec.unpercent(t))) : ${R}}:
  %Equal.sym(Maybe<&2, U32>, Spec.hexdig(b), hpick(b, Bytes.hex(b)), hex(b)) : {${go("t", "Url.percent_step(a, b, rev, Bytes.hex(b))")} == prepend(rev, Spec.escaped(Some{va}, _, Spec.unpercent(t))) : ${R}}
  esc_lo(a, va, b, t, rev, sh, Bytes.hex(b), {==}, ih)
`);

emit(
  `def esc_bits(${bitParams}, +b: U32, +t: ${L}, +rev: ${L}, ih: ${IH("t")}) -> {${go("t", `Url.percent_step(${byteA}, b, rev, Bytes.hex(${byteA}) && Bytes.hex(b))`)} == prepend(rev, Spec.escaped(Spec.hexdig(${byteA}), Spec.hexdig(b), Spec.unpercent(t))) : ${R}}:`,
);
msbSplit(
  2,
  () => "fail_stays(t, Url.InvalidPercent{})",
  (code) =>
    isHex(code)
      ? `esc_hi(${code}, ${nibble(code)}, b, t, rev, {==}, ih)`
      : "fail_stays(t, Url.InvalidPercent{})",
);
emit(``);
emit(
  `def esc(+a: U32, +b: U32, +t: ${L}, +rev: ${L}, ih: ${IH("t")}) -> {${go("t", "Url.percent_step(a, b, rev, Bytes.hex(a) && Bytes.hex(b))")} == prepend(rev, Spec.escaped(Spec.hexdig(a), Spec.hexdig(b), Spec.unpercent(t))) : ${R}}:`,
);
emit(`  match a:`);
emit(`    case U32{${bitPattern}}:`);
emit(`      esc_bits(${bitArgs}, b, t, rev, ih)`);
emit(``);

// ---- the main induction ----
emit(`# The implementation's accumulator loop is the spec with its reversed
# output in front.
def equiv(+xs: ${L}, +rev: ${L}) -> {${go("xs", "Done{rev}")} == prepend(rev, Spec.unpercent(xs)) : ${R}}:
  match xs:
    case Nil{}: {==}
    case U32{+w0} <> +t:`);
headTrie(
  6,
  (head) => `lit_step(${head}, t, rev, equiv(t, ${head} <> rev))`,
  (pad) => {
    const sp = " ".repeat(pad);
    emit(`${sp}match t:`);
    emit(`${sp} case Nil{}: {==}`);
    emit(`${sp} case +a <> Nil{}: {==}`);
    emit(`${sp} case +a <> +b <> +u: esc(a, b, u, rev, r => equiv(u, r))`);
  },
);
emit(``);
emit(`def percent(+xs: ${L}) -> {Url.percent_decode(xs, False{}) == Spec.unpercent(xs) : ${R}}:
  Equal.trans(${R}, Url.percent_decode(xs, False{}), prepend([], Spec.unpercent(xs)), Spec.unpercent(xs), equiv(xs, []), prepend_nil(Spec.unpercent(xs)))`);

process.stdout.write(lines.join("\n") + "\n");
