#!/usr/bin/env python3
"""Emit the BND-86 walk lemmas: matching a prefix followed by a member is the
specification's prefix walk, for each case mode. Prints Bend to stdout; the
output is pasted into proof/mount-decompose.bend between the GENERATED marks."""

MODES = [
    ("walk_sensitive", "MS.matches", "True{}", "String.eq({raw}, {h})"),
    ("walk_folded", "S.folded", "False{}", "S.folded_text({raw}, {h})"),
]

M = "Maybe<&2, P.Params>"


def app(x):
    return f"List.append(&2, P.Segment, {x}, b)"


def lemma(name, mt, c, text):
    wild = f"{name}_wildcard"
    pre = f"{name}_prefix"
    out = []
    out.append(f"""def {wild}(+n: String, after: List<&2, P.Segment>, +ys: List<&2, String>, +taken: List<&2, String>) ->
    {{{mt}(P.Wildcard{{n}} <> after, ys, taken) == S.wildcard_end(n, after, ys) : {M}}}:
  match after:
    case Nil{{}}:
      {{==}}
    case x <> y:
      {{==}}

def {pre}(+p: String, after: List<&2, P.Segment>, ys: List<&2, String>, +taken: List<&2, String>) ->
    {{{mt}(P.PrefixWildcard{{p}} <> after, ys, taken) == S.prefix_end({c}, p, after, ys) : {M}}}:
  match after ys:
    case Nil{{}} h <> u:
      {{==}}
    case Nil{{}} Nil{{}}:
      {{==}}
    case x <> y zs:
      {{==}}
""")
    goal = lambda a, xs, tk: f"{{{mt}({app(a)}, {xs}, {tk}) == S.walk({a}, {xs}, {c}, b, {tk}) : {M}}}"
    ih = lambda a, xs, tk: f"{name}({a}, b, {xs}, {tk})"
    iw_l = f"MS.or_else({mt}({app('t')}, h <> u, Nil{{}}), x => {mt}(P.InteriorWildcard{{}} <> {app('t')}, u, Nil{{}}))"
    sp_l = f"MS.or_else({mt}(P.Span{{n}} <> {app('t')}, u, h <> taken), x => MS.span_here(n, h <> taken, {mt}({app('t')}, u, Nil{{}})))"
    out.append(f"""def {name}(+a: List<&2, P.Segment>, +b: List<&2, P.Segment>, +xs: List<&2, String>, +taken: List<&2, String>) ->
    {goal('a', 'xs', 'taken')}:
  match a xs:
    case Nil{{}} ys:
      {{==}}
    case P.Static{{raw}} <> t Nil{{}}:
      {{==}}
    case P.Static{{+raw}} <> +t +h <> +u:
      Equal.cong({M}, {M}, r => MS.same_text({text.format(raw='raw', h='h')}, r), {mt}({app('t')}, u, Nil{{}}), S.walk(t, u, {c}, b, Nil{{}}), {ih('t', 'u', 'Nil{}')})
    case P.Capture{{n, k, True{{}}}} <> +t Nil{{}}:
      {ih('t', 'Nil{}', 'Nil{}')}
    case P.Capture{{n, k, False{{}}}} <> t Nil{{}}:
      {{==}}
    case P.Capture{{+n, +k, True{{}}}} <> +t +h <> +u:
      Equal.cong({M}, {M}, r => MS.capture(n, k, E.decode(h), r), {mt}({app('t')}, u, Nil{{}}), S.walk(t, u, {c}, b, Nil{{}}), {ih('t', 'u', 'Nil{}')})
    case P.Capture{{+n, +k, False{{}}}} <> +t +h <> +u:
      Equal.cong({M}, {M}, r => MS.capture(n, k, E.decode(h), r), {mt}({app('t')}, u, Nil{{}}), S.walk(t, u, {c}, b, Nil{{}}), {ih('t', 'u', 'Nil{}')})
    case P.Wildcard{{+n}} <> +t ys:
      {wild}(n, {app('t')}, ys, taken)
    case P.InteriorWildcard{{}} <> +t Nil{{}}:
      {ih('t', 'Nil{}', 'Nil{}')}
    case P.InteriorWildcard{{}} <> +t +h <> +u:
      %{ih('t', 'h <> u', 'Nil{}')} : {{{iw_l} == MS.or_else(_, x => S.walk(P.InteriorWildcard{{}} <> t, u, {c}, b, Nil{{}})) : {M}}}
      %{ih('P.InteriorWildcard{} <> t', 'u', 'Nil{}')} : {{{iw_l} == MS.or_else({mt}({app('t')}, h <> u, Nil{{}}), x => _) : {M}}}
      {{==}}
    case P.PrefixWildcard{{+p}} <> +t ys:
      {pre}(p, {app('t')}, ys, taken)
    case P.Span{{n}} <> t Nil{{}}:
      {{==}}
    case P.Span{{+n}} <> +t +h <> +u:
      %{ih('P.Span{n} <> t', 'u', 'h <> taken')} : {{{sp_l} == MS.or_else(_, x => MS.span_here(n, h <> taken, S.walk(t, u, {c}, b, Nil{{}}))) : {M}}}
      %{ih('t', 'u', 'Nil{}')} : {{{sp_l} == MS.or_else({mt}(P.Span{{n}} <> {app('t')}, u, h <> taken), x => MS.span_here(n, h <> taken, _)) : {M}}}
      {{==}}
""")
    return "\n".join(out)


print("# GENERATED by scripts/mount-walk-proofs.py: begin")
for m in MODES:
    print(lemma(*m))
print("# GENERATED by scripts/mount-walk-proofs.py: end")
