// Generates proof/base64-chars.bend: for every character c, a standard
// alphabet value w of c satisfies Base64.symbol(w, False{}) == c. One
// decision trie over the character's 32 bits proves it. Base64.value
// compiles to a trie over the same bits, low bit first, so each branch of
// this proof stops where Base64.value reaches its default.
//
//   bun scripts/gen-base64-chars.ts > proof/base64-chars.bend

const upper = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const lower = "abcdefghijklmnopqrstuvwxyz";
const digits = "0123456789";
// Every literal Base64.value matches, in both alphabets.
const matched = [...upper, ...lower, ...digits, "+", "-", "/", "_"];

function bit(char: string, position: number): boolean {
  return ((char.codePointAt(0) ?? 0) >> position) % 2 === 1;
}

// '-' and '_' have no standard value, so their Back type is Unit.
function leaf(char: string): string {
  return char === "-" || char === "_" ? "Unit{}" : "{==}";
}

const dead = "Unit{}";
const lines: string[] = [];

function trie(depth: number, chars: string[], indent: number): void {
  const pad = " ".repeat(indent);
  const [only] = chars;
  if (depth === 32 && only !== undefined) {
    lines.push(`${pad}match w32:`);
    lines.push(`${pad} case WNil{}: ${leaf(only)}`);
    return;
  }
  lines.push(`${pad}match w${depth}:`);
  for (const value of [true, false]) {
    const rest = chars.filter((char) => bit(char, depth) === value);
    const pattern = `case WCon{${value ? "True" : "False"}{}, w${depth + 1}}:`;
    if (rest.length === 0) {
      lines.push(`${pad} ${pattern} ${dead}`);
    } else {
      lines.push(`${pad} ${pattern}`);
      trie(depth + 1, rest, indent + 2);
    }
  }
}

const header = `# BND-87: every standard-alphabet Base64 value names its own character, as
# one decision trie over the character's 32 bits, low bit first, mirroring
# Base64.value. Each branch stops once no alphabet character shares its
# bits, so Base64.value has already reached its default there.
#
# GENERATED by scripts/gen-base64-chars.ts. Do not edit by hand.
import Base
import ../src/data/base64.bend as B

# What a character's standard value tells: the symbol of that value is the
# character itself. A character without a value tells nothing.
def Back(c: Char, m: Maybe<&2, Word(6n)>) -> Type:
  match m:
    case None{}: Unit
    case Some{w}: {B.symbol(w, False{}) == c : Char}

`;

lines.push("def chars(+c: Char) -> Back(c, B.value(c, False{})):");
lines.push(" match c:");
lines.push("  case Chr{U32{w0}}:");
trie(0, matched, 3);
process.stdout.write(header + lines.join("\n") + "\n");

