#!/usr/bin/env python3
"""Generate src/router/compile-spec-chars.bend (BND-83).

Pattern.compile matches literal characters (`{` and `?` in split_name, the
string "*" in compile, located and invalid_tail). A literal match compiles to a
trie over the character's 32 bits, least significant first, so a proof over an
abstract character must split those bits until every row of the trie
decides. This script lists the off-path rows; the literal rows themselves are
written as character patterns.

Run: python3 scripts/route-compile-proofs.py
"""

from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/router/compile-spec-chars.bend"


def off_path(literals: list[int]) -> list[list[int]]:
    """Bit prefixes (LSB first) where no literal continues."""
    rows: list[list[int]] = []

    def go(prefix: list[int], candidates: list[int]) -> None:
        depth = len(prefix)
        if depth == 32:
            return
        for bit in (0, 1):
            rest = [c for c in candidates if (c >> depth) & 1 == bit]
            if rest:
                go(prefix + [bit], rest)
            else:
                rows.append(prefix + [bit])

    go([], literals)
    return rows


def word(bits: list[int], tail: str) -> str:
    out = tail
    for bit in reversed(bits):
        out = f"WCon{{{'True' if bit else 'False'}{{}}, {out}}}"
    return f"Chr{{U32{{{out}}}}}"


def cases(literals: list[int], indent: str, row) -> str:
    lines = []
    for bits in off_path(literals):
        pattern = word(bits, "+w")
        value = word(bits, "w")
        head, body = row(pattern, value)
        lines.append(f"{indent}case {head}:")
        lines.append(f"{indent}  {body}")
    return "\n".join(lines)


BRACE_OR_QUESTION = [ord("{"), ord("?")]
STAR = [ord("*")]

PRELUDE = """\
# GENERATED by scripts/route-compile-proofs.py. Do not edit by hand.
# BND-83: bit-level case splits for the literal characters Pattern.compile
# matches, so its helpers reduce on an abstract character.
import Base
import ./pattern.bend as P
import ./constraint.bend as C
import ./encoding.bend as E
import ./codec-bits.bend as Bits
import ../../proof/router-compile-spec.bend as S

def as_split(c: S.Cut) -> C.Split:
  match c:
    case S.Cut{name, suffix}:
      C.Split{name, suffix}

def whole(c: S.Cut) -> String:
  match c:
    case S.Cut{name, suffix}:
      name ++ suffix

def cons_split(h: Char, c: S.Cut) -> {C.split_cons(h, as_split(c)) == as_split(S.cut_cons(h, c)) : C.Split}:
  match c:
    case S.Cut{name, suffix}:
      {==}

def cons_whole(+h: Char, c: S.Cut) -> {whole(S.cut_cons(h, c)) == SCon{h, whole(c)} : String}:
  match c:
    case S.Cut{name, suffix}:
      {==}

def split_step(+h: Char, +t: String, ih: {P.split_name(t) == as_split(S.cut(t)) : C.Split}) ->
    {C.split_cons(h, P.split_name(t)) == as_split(S.cut_cons(h, S.cut(t))) : C.Split}:
  Equal.trans(C.Split, C.split_cons(h, P.split_name(t)), C.split_cons(h, as_split(S.cut(t))), as_split(S.cut_cons(h, S.cut(t))), Equal.cong(C.Split, C.Split, x => C.split_cons(h, x), P.split_name(t), as_split(S.cut(t)), ih), cons_split(h, S.cut(t)))

def whole_step(+h: Char, +t: String, ih: {whole(S.cut(t)) == t : String}) ->
    {whole(S.cut_cons(h, S.cut(t))) == SCon{h, t} : String}:
  Equal.trans(String, whole(S.cut_cons(h, S.cut(t))), SCon{h, whole(S.cut(t))}, SCon{h, t}, cons_whole(h, S.cut(t)), Equal.cong(String, String, x => SCon{h, x}, whole(S.cut(t)), t, ih))

# The compiler's name split is the spec's cut.
def split_cut(s: String) -> {P.split_name(s) == as_split(S.cut(s)) : C.Split}:
  match s:
    case SNil{}:
      {==}
    case SCon{'{', t}:
      {==}
    case SCon{'?', t}:
      {==}
@SPLIT@

# The cut loses nothing: name ++ suffix is the source.
def cut_whole(s: String) -> {whole(S.cut(s)) == s : String}:
  match s:
    case SNil{}:
      {==}
    case SCon{'{', t}:
      {==}
    case SCon{'?', t}:
      {==}
@WHOLE@

# A valid name is never the bare `*`, so locating it keeps the wildcard.
def located_named(t: String, +rest: List<&2, String>, ok: {P.name_ok(t) == True{} : Bool}) ->
    {P.located(P.Wildcard{t}, rest) == P.Wildcard{t} : P.Segment}:
  match t:
    case SNil{}:
      Bits.absurd({P.located(P.Wildcard{""}, rest) == P.Wildcard{""} : P.Segment}, Bits.false_true(ok))
    case "*":
      Bits.absurd({P.located(P.Wildcard{"*"}, rest) == P.Wildcard{"*"} : P.Segment}, Bits.false_true(ok))
    case SCon{'*', SCon{+h, +u}}:
      Bits.absurd({P.located(P.Wildcard{SCon{'*', SCon{h, u}}}, rest) == P.Wildcard{SCon{'*', SCon{h, u}}} : P.Segment}, Bits.false_true(ok))
@NAMED@

# When the compiler's raw-source tail check rejects a segment.
def misplaced(s: P.Segment, rest: List<&2, String>) -> Bool:
  match s:
    case P.Static{raw}:
      False{}
    case P.Capture{name, c, o}:
      match o:
        case True{}:
          Bool.not(P.optional_sources(rest))
        case False{}:
          False{}
    case P.Wildcard{name}:
      Bool.not(List.is_empty(&2, String, rest))
    case P.InteriorWildcard{}:
      False{}
    case P.PrefixWildcard{p}:
      Bool.not(List.is_empty(&2, String, rest))
    case P.Span{name}:
      False{}

def wild_inv(m: String, +rest: List<&2, String>) ->
    {P.invalid_tail(P.located(P.Wildcard{m}, rest), rest) == misplaced(P.located(P.Wildcard{m}, rest), rest) : Bool}:
  match m rest:
    case SNil{} r:
      {==}
    case "*" Nil{}:
      {==}
    case "*" h <> t:
      {==}
    case SCon{'*', SCon{h, u}} r:
      {==}
@WILD@

# The tail check on a located segment is misplaced.
def tail_inv(p: P.Segment, +rest: List<&2, String>) ->
    {P.invalid_tail(P.located(p, rest), rest) == misplaced(P.located(p, rest), rest) : Bool}:
  match p:
    case P.Wildcard{m}:
      wild_inv(m, rest)
    case P.Static{raw}:
      {==}
    case P.Capture{name, c, True{}}:
      {==}
    case P.Capture{name, c, False{}}:
      {==}
    case P.InteriorWildcard{}:
      {==}
    case P.PrefixWildcard{x}:
      {==}
    case P.Span{name}:
      {==}

def top_step(+h: Char, +t: String, b: Bool,
    bodies: @u: String -> {S.accepted(P.compile_body(u)) == S.body(u) : Maybe<&2, P.Pattern>}) ->
    {S.accepted(E.choose(Result<&2, &2, P.PatternError, P.Pattern>, b, u => P.compile_body(t), u => Fail{P.PatternError{P.MissingSlash{}, SCon{h, t}}})) == S.slash(b, t) : Maybe<&2, P.Pattern>}:
  match b:
    case True{}:
      bodies(t)
    case False{}:
      {==}

# Given the body law, the whole compiler is the spec, bare `*` included.
def top(src: String, bodies: @u: String -> {S.accepted(P.compile_body(u)) == S.body(u) : Maybe<&2, P.Pattern>}) ->
    {S.accepted(P.compile(src)) == S.compile(src) : Maybe<&2, P.Pattern>}:
  match src:
    case SNil{}:
      {==}
    case "*":
      bodies("*")
    case SCon{'*', SCon{+h, +t}}:
      {==}
@TOP@
"""


def main() -> None:
    text = PRELUDE
    text = text.replace(
        "@SPLIT@",
        cases(BRACE_OR_QUESTION, "    ", lambda p, v: (f"SCon{{{p}, +t}}", f"split_step({v}, t, split_cut(t))")),
    )
    text = text.replace(
        "@WHOLE@",
        cases(BRACE_OR_QUESTION, "    ", lambda p, v: (f"SCon{{{p}, +t}}", f"whole_step({v}, t, cut_whole(t))")),
    )
    text = text.replace("@NAMED@", cases(STAR, "    ", lambda p, v: (f"SCon{{{p}, u}}", "{==}")))
    text = text.replace("@WILD@", cases(STAR, "    ", lambda p, v: (f"SCon{{{p}, u}} r", "{==}")))
    text = text.replace(
        "@TOP@",
        cases(STAR, "    ", lambda p, v: (f"SCon{{{p}, +t}}", f"top_step({v}, t, Char.is_eq({v}, '/'), bodies)")),
    )
    OUT.write_text(text)


if __name__ == "__main__":
    main()
