// Generates proof/base64url-chars.bend: three facts about every character's
// base64url value, proven by one decision trie over the character's 32 bits.
// Base64.value compiles to a trie over the same bits, low bit first, so each
// branch of this proof stops where Base64.value reaches its default.
//
//   bun scripts/gen-base64url-chars.ts > proof/base64url-chars.bend

const upper = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const lower = "abcdefghijklmnopqrstuvwxyz";
const digits = "0123456789";
// The URL alphabet in value order, and every literal Base64.value matches.
const url = [...upper, ...lower, ...digits, "-", "_"];
const matched = [...upper, ...lower, ...digits, "+", "-", "/", "_"];

function multipleOf(step: number): string[] {
  return url.filter((_, index) => index % step === 0);
}

type Fact = { members: string[]; type: (char: string) => string };
const word = "Maybe<&2, Word(6n)>";
const facts: [Fact, Fact, Fact] = [
  { members: url, type: (c) => `{B.value(${c}, True{}) == None{} : ${word}}` },
  { members: multipleOf(16), type: (c) => `{bad4(B.value(${c}, True{})) == True{} : Bool}` },
  { members: multipleOf(4), type: (c) => `{bad2(B.value(${c}, True{})) == True{} : Bool}` },
];

function literal(char: string): string {
  return `'${char}'`;
}

function bit(char: string, position: number): boolean {
  return ((char.codePointAt(0) ?? 0) >> position) % 2 === 1;
}

const dead = "(e1 => {==}, (e2 => {==}, e3 => {==}))";

function leaf(char: string): string {
  const [a, b, c] = facts.map((fact, i) => {
    const name = `e${i + 1}`;
    return fact.members.includes(char)
      ? `${name} => nope(${fact.type(literal(char))}, ${name})`
      : `${name} => {==}`;
  });
  return `(${a}, (${b}, ${c}))`;
}

const lines: string[] = [];

function trie(depth: number, chars: string[], indent: number): void {
  const pad = " ".repeat(indent);
  const [only] = chars;
  if (depth === 32 && only !== undefined) {
    lines.push(`${pad}match w32:`);
    lines.push(`${pad} case WNil{}: ${leaf(only)}`);
    return;
  }
  lines.push(`${pad}match w${depth}:`);
  for (const value of [true, false]) {
    const rest = chars.filter((char) => bit(char, depth) === value);
    const pattern = `case WCon{${value ? "True" : "False"}{}, w${depth + 1}}:`;
    if (rest.length === 0) {
      lines.push(`${pad} ${pattern} ${dead}`);
    } else {
      lines.push(`${pad} ${pattern}`);
      trie(depth + 1, rest, indent + 2);
    }
  }
}

const header = `# BND-43: facts about every character's base64url value, as one decision trie
# over the character's 32 bits, low bit first, mirroring Base64.value. Each
# branch stops once no alphabet character shares its bits, so Base64.value
# has already reached its default there.
#
# GENERATED by scripts/gen-base64url-chars.ts. Do not edit by hand.
import Base
import ../src/data/base64.bend as B
import ../src/data/utf8.bend as U
import ./jwt.bend as JwtProof
import ./jwt-spec.bend as Spec

def nope(-A: Type, e: {True{} == False{} : Bool}) -> A:
  JwtProof.absurd(A, JwtProof.false_true(Equal.sym(Bool, True{}, False{}, e)))

# None, or a final character whose low four bits (unused after two final
# characters) are not all zero.
def bad4(m: Maybe<&2, Word(6n)>) -> Bool:
  match m:
    case None{}: True{}
    case Some{w}: Bool.not(U.zero(4n, U.low(4n, 2n, w)))

# None, or a final character whose low two bits (unused after three final
# characters) are not all zero.
def bad2(m: Maybe<&2, Word(6n)>) -> Bool:
  match m:
    case None{}: True{}
    case Some{w}: Bool.not(U.zero(2n, U.low(2n, 4n, w)))

def Facts(c: Char) -> Type:
  (${facts[0].type("c").replace("{B.value", "{Spec.url_char(c) == False{} : Bool} -> {B.value")}) & (({Spec.last4(c) == False{} : Bool} -> ${facts[1].type("c")}) & ({Spec.last2(c) == False{} : Bool} -> ${facts[2].type("c")}))

`;

lines.push("def chars(+c: Char) -> Facts(c):");
lines.push(" match c:");
lines.push("  case Chr{U32{w0}}:");
trie(0, matched, 3);
process.stdout.write(header + lines.join("\n") + "\n");
