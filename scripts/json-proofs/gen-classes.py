#!/usr/bin/env python3
"""Generate proof/json-classes.bend: literal-character dispatch facts.

Each lemma splits a U32 bit by bit, least significant first, only along the
prefixes some literal shares. Branches that leave every literal behind reduce
on both sides; a branch that spells a literal contradicts its is_eq premise.

Run from the repository root: python3 scripts/json-proofs/gen-classes.py
"""

from pathlib import Path

T, F = "True{}", "False{}"


def word(bits, tail):
    s = tail
    for b in reversed(bits):
        s = f"WCon{{{b}, {s}}}"
    return s


def trie(name, params, goal, literals):
    """goal is a format string over {c}; literals maps value -> premise name."""
    out = [f"def {name}(+c: U32, {params}) -> {goal.format(c='c')}:", "  match c:"]

    def go(prefix):
        live = [v for v in literals if all(((v >> i) & 1) == (1 if b == T else 0) for i, b in enumerate(prefix))]
        if not live:
            out.append(f"    case U32{{{word(prefix, 't')}}}: {{==}}")
            return
        if len(prefix) == 32:
            (v,) = live
            out.append(f"    case U32{{{word(prefix, 'WNil{}')}}}:")
            out.append(f"      P.absurd({goal.format(c=str(v))}, P.false_true(Equal.sym(Bool, True{{}}, False{{}}, {literals[v]})))")
            return
        go(prefix + [F])
        go(prefix + [T])

    go([])
    out.append("")
    return "\n".join(out)


def premises(literals):
    return ", ".join(f"{n}: {{U32.is_eq(c, {v}) == False{{}} : Bool}}" for v, n in literals.items())


HEAD = """# Literal-character dispatch in the JSON writer and parser, for characters
# known only through is_eq premises. Generated by
# scripts/json-proofs/gen-classes.py.
import Base
import ../src/data/json.bend as J
import ./utf8.bend as P
"""


def main():
    parts = [HEAD]
    esc = {34: "q", 92: "s", 8: "bs", 12: "ff", 10: "nl", 13: "cr", 9: "tab"}
    parts.append(trie(
        "escape_class", "+ascii: Bool, " + premises(esc),
        "{{J.escape_char({c}, ascii) == J.escaped_other({c}, ({c} < 32 : U32) || (ascii && ({c} > 127 : U32))) : String}}",
        esc))
    space = {32: "sp", 9: "tab", 10: "nl", 13: "cr"}
    parts.append(trie("not_space", premises(space), "{{J.whitespace({c}) == False{{}} : Bool}}", space))
    starts = {110: "n", 116: "t", 102: "f", 34: "q", 91: "a", 123: "o"}
    parts.append(trie(
        "value_number", "+r: String, +fs: List<&2, J.Frame>, +d: Nat, " + premises(starts),
        "{{J.token(J.MValue{{}}, SCon{{Chr{{{c}}}, r}}, fs, d) == J.number_next(J.number_step(J.PStart{{}}, {c}), J.PStart{{}}, \"\", {c}, r, fs, d) : J.Machine}}",
        starts))
    close = {93: "close"}
    parts.append(trie(
        "first_value", "+r: String, +fs: List<&2, J.Frame>, +d: Nat, " + premises(close),
        "{{J.token(J.MArrayFirst{{}}, SCon{{Chr{{{c}}}, r}}, fs, d) == J.Machine{{J.MValue{{}}, SCon{{Chr{{{c}}}, r}}, J.ArrayFrame{{[]}} <> fs, d}} : J.Machine}}",
        close))
    Path("proof/json-classes.bend").write_text("\n".join(parts))


if __name__ == "__main__":
    main()
