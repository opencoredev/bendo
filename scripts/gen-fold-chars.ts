// Generates proof/fold-chars.bend: Base's Char.to_lower equals the
// independent letter table of proof/fold-spec.bend for every U32.
//
// Both sides compare the character with constants below 256, and Word.cmp
// decides from the top bit, so the proof splits the top 24 bits first (any
// set bit means "not a capital" and both sides keep the character), then
// all 8 low bits, where every leaf is a closed computation.
//
//   bun scripts/gen-fold-chars.ts > proof/fold-chars.bend

const lines: string[] = [];
const emit = (line: string): void => {
  lines.push(line);
};
const flag = (b: boolean): string => (b ? "True{}" : "False{}");
const bits = [...Array(32).keys()];
const params = [...bits]
  .reverse()
  .map((i) => `+b${i}: Bool`)
  .join(", ");
const args = [...bits]
  .reverse()
  .map((i) => `b${i}`)
  .join(", ");
const pattern = bits.reduceRight((acc, i) => `WCon{+b${i}, ${acc}}`, "WNil{}");
const word = (known: Map<number, boolean>): string =>
  `U32{${bits.reduceRight((acc, i) => {
    const b = known.get(i);
    return `WCon{${b === undefined ? `b${i}` : flag(b)}, ${acc}}`;
  }, "WNil{}")}}`;
const goal = (c: string): string =>
  `{Char.to_lower(Chr{${c}}) == Spec.small(Chr{${c}}, Spec.letters()) : Char}`;

emit(`# BND-92: Base's Char.to_lower equals the independent letter table for
# every character, so Bytes.fold equals the table fold for every String.
#
# GENERATED by scripts/gen-fold-chars.ts. Do not edit by hand.
import Base
import ./fold-spec.bend as Spec

def adc_zero(+n: Nat, +w: Word(n)) -> {Word.adc(n, w, Word.zero(n), False{}, False{}) == w : Word(n)}:
  match n:
    case 0n:
      match w:
        case WNil{}: {==}
    case 1n+p:
      match w:
        case WCon{False{}, t}:
          %adc_zero(p, t) : {WCon{False{}, Word.adc(p, t, Word.zero(p), False{}, False{})} == WCon{False{}, _} : Word(1n+p)}
          {==}
        case WCon{True{}, t}:
          %adc_zero(p, t) : {WCon{True{}, Word.adc(p, t, Word.zero(p), False{}, False{})} == WCon{True{}, _} : Word(1n+p)}
          {==}

# A character that is not a capital is kept: Char.to_lower adds zero.
def keep(+x: U32) -> {Chr{U32.add(x, 0)} == Chr{x} : Char}:
  match x:
    case U32{w}:
      Equal.cong(Word(32n), Char, v => Chr{U32{v}}, Word.adc(32n, w, Word.zero(32n), False{}, False{}), w, adc_zero(32n, w))
`);

emit(`def char_bits(${params}) -> ${goal(word(new Map()))}:`);
const walk = (bit: number, known: Map<number, boolean>, pad: number): void => {
  const sp = " ".repeat(pad);
  emit(`${sp}match b${bit}:`);
  if (bit >= 8) {
    const set = new Map(known).set(bit, true);
    emit(`${sp} case True{}: keep(${word(set)})`);
    emit(`${sp} case False{}:`);
    walk(bit - 1, new Map(known).set(bit, false), pad + 2);
    return;
  }
  for (const b of [true, false]) {
    const next = new Map(known).set(bit, b);
    if (bit === 0) emit(`${sp} case ${flag(b)}: {==}`);
    else {
      emit(`${sp} case ${flag(b)}:`);
      walk(bit - 1, next, pad + 2);
    }
  }
};
walk(31, new Map(), 2);
emit(``);
emit(`def char(+c: U32) -> ${goal("c")}:`);
emit(`  match c:`);
emit(`    case U32{${pattern}}:`);
emit(`      char_bits(${args})`);

process.stdout.write(lines.join("\n") + "\n");

export {};
