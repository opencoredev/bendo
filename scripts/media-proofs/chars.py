#!/usr/bin/env python3
"""Generate proof/media-chars.bend: no character of a well-formed media type
is whitespace to Base's Char.is_space (BND-85).

Word.cmp settles a comparison with a small constant as soon as a high bit is
set, so the proof splits bits 31 down to 8 one at a time (a set bit closes
the case) and then every combination of the low 8 bits.
Run: python3 scripts/media-proofs/chars.py > proof/media-chars.bend
"""

HIGH = list(range(31, 7, -1))
LOW = list(range(7, -1, -1))


def word():
    inner = "WNil{}"
    for i in range(31, -1, -1):
        inner = f"WCon{{b{i}, {inner}}}"
    return inner


def low_tree(bits, indent):
    pad = "  " * indent
    if not bits:
        return [f"{pad}{{==}}"]
    b, rest = bits[0], bits[1:]
    lines = [f"{pad}match b{b}:"]
    for value in ("False{}", "True{}"):
        lines.append(f"{pad}  case {value}:")
        lines.extend(low_tree(rest, indent + 2))
    return lines


def high_tree(bits, indent):
    pad = "  " * indent
    if not bits:
        return low_tree(LOW, indent)
    b, rest = bits[0], bits[1:]
    lines = [f"{pad}match b{b}:", f"{pad}  case True{{}}: {{==}}", f"{pad}  case False{{}}:"]
    lines.extend(high_tree(rest, indent + 2))
    return lines


def main():
    params_low_first = ", ".join(f"b{i}: Bool" for i in range(32))
    params_top_first = ", ".join(f"b{i}: Bool" for i in range(31, -1, -1))
    args_low_first = ", ".join(f"b{i}" for i in range(32))
    args_top_first = ", ".join(f"b{i}" for i in range(31, -1, -1))
    out = [
        "# Generated by scripts/media-proofs/chars.py; do not edit (BND-85).",
        "# A token character or '/' is never whitespace to Base's Char.is_space,",
        "# for every U32.",
        "import Base",
        "import ./media-spec.bend as Spec",
        "",
        f"def bits({params_low_first}) -> U32:",
        f"  U32{{{word()}}}",
        "",
        "# Whitespace to Char.is_space that is also a media-type character.",
        "def clash(+c: U32) -> Bool:",
        "  Char.is_space(Chr{c}) && (Spec.tchar(c) || Spec.slash(c))",
        "",
        f"def clash_bits({params_top_first}) -> {{clash(bits({args_low_first})) == False{{}} : Bool}}:",
    ]
    out.extend(high_tree(HIGH, 1))
    out += [
        "",
        "def no_clash(+c: U32) -> {clash(c) == False{} : Bool}:",
        "  match c:",
        f"    case U32{{{word()}}}: clash_bits({args_top_first})",
        "",
    ]
    print("\n".join(out))


main()
